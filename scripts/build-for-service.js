#!/usr/bin/env node

/**
 * Build script for generating browser extensions for different Pocket-like backends
 * Usage: node build-for-service.js [service-name] [consumer-key]
 * 
 * Examples:
 * node build-for-service.js pocket YOUR_POCKET_CONSUMER_KEY
 * node build-for-service.js readlater YOUR_READLATER_CONSUMER_KEY
 */

const fs = require('fs')
const path = require('path')

// Available service configurations
const SERVICE_CONFIGS = {
  pocket: {
    SERVICE_NAME: 'Pocket',
    BASE_DOMAIN: 'getpocket.com',
    API_VERSION: 'v3',
    BRANDING: {
      name: 'Save to Pocket',
      shortName: 'Pocket',
      description: 'The easiest, fastest way to capture articles, videos, and more.',
    }
  },
  readlater: {
    SERVICE_NAME: 'ReadLater',
    BASE_DOMAIN: 'example-readlater.com',
    API_VERSION: 'v1',
    BRANDING: {
      name: 'Save to ReadLater',
      shortName: 'ReadLater',
      description: 'Save articles and content for later reading.',
    }
  }
}

function generateConfigFile(serviceName, consumerKey) {
  const config = SERVICE_CONFIGS[serviceName.toLowerCase()]
  if (!config) {
    console.error(`Unknown service: ${serviceName}`)
    console.error(`Available services: ${Object.keys(SERVICE_CONFIGS).join(', ')}`)
    process.exit(1)
  }

  const configContent = `// Configuration for ${config.SERVICE_NAME} backend
// This file is auto-generated by build-for-service.js

// Active configuration for ${config.SERVICE_NAME}
const ACTIVE_CONFIG = ${JSON.stringify(config, null, 2)}

// Generate URLs based on active configuration
export const CONFIG = {
  ...ACTIVE_CONFIG,
  URLS: {
    AUTH: \`https://\${ACTIVE_CONFIG.BASE_DOMAIN}/signup?src=extension&route=/extension_login_success\`,
    LOGOUT: \`https://\${ACTIVE_CONFIG.BASE_DOMAIN}/lo\`,
    API_BASE: \`https://\${ACTIVE_CONFIG.BASE_DOMAIN}/\${ACTIVE_CONFIG.API_VERSION}/\`,
    USER_LIST: \`https://\${ACTIVE_CONFIG.BASE_DOMAIN}/saves\`,
    USER_HOME: \`https://\${ACTIVE_CONFIG.BASE_DOMAIN}/home\`,
    HELP: \`https://help.\${ACTIVE_CONFIG.BASE_DOMAIN}/\`,
    CONTACT: \`https://\${ACTIVE_CONFIG.BASE_DOMAIN}/contact_support?field3=Question%20about%20\${ACTIVE_CONFIG.SERVICE_NAME}%20Extension\`,
    PRIVACY: \`https://\${ACTIVE_CONFIG.BASE_DOMAIN}/privacy/?src=extension\`,
    TERMS: \`https://\${ACTIVE_CONFIG.BASE_DOMAIN}/tos/?src=extension\`,
  }
}

// Consumer key for ${config.SERVICE_NAME}
export const CONSUMER_KEY = '${consumerKey}'

// Extension-specific constants that don't change
export const EXTENSION_CONSTANTS = {
  SET_SHORTCUTS: 'chrome://extensions/configureCommands',
  LOGIN_SUCCESS_PATH: '/extension_login_success*',
  LOGOUT_ERROR_PATH: '/login?e=4'
}
`

  return configContent
}

function generateManifest(serviceName) {
  const config = SERVICE_CONFIGS[serviceName.toLowerCase()]
  
  const manifest = {
    "manifest_version": 3,
    "name": config.BRANDING.name,
    "default_locale": "en",
    "description": config.BRANDING.description,
    "icons": {
      "16": "assets/images/icon-16.png",
      "48": "assets/images/icon-48.png",
      "128": "assets/images/icon-128.png"
    },
    "action": {
      "default_icon": {
        "38": "assets/images/action-icon.png"
      },
      "default_title": config.BRANDING.name
    },
    "background": {
      "service_worker": "pages/background/index.js"
    },
    "options_page": "pages/options/options.html",
    "content_scripts": [
      {
        "matches": [
          "*://*/*"
        ],
        "js": [
          "pages/injector/content.js"
        ],
        "css": [
          "assets/fonts/fonts.css",
          "assets/pocket-save-extension.css"
        ]
      },
      {
        "matches": [
          `*://${config.BASE_DOMAIN}/extension_login_success*`
        ],
        "js": [
          "pages/login.js"
        ]
      },
      {
        "matches": [
          `*://${config.BASE_DOMAIN}/login?e=4`
        ],
        "js": [
          "pages/logout.js"
        ]
      }
    ],
    "host_permissions": [
      `*://${config.BASE_DOMAIN}/*`
    ],
    "permissions": [
      "tabs",
      "contextMenus",
      "cookies",
      "storage"
    ],
    "commands": {
      "save-to-pocket-action": {
        "suggested_key": {
          "default": "Ctrl+Shift+P",
          "windows": "Ctrl+Shift+P",
          "mac": "Command+Shift+P",
          "chromeos": "Ctrl+Shift+P",
          "linux": "Ctrl+Shift+P"
        },
        "description": `Save page to ${config.BRANDING.shortName}`
      }
    }
  }

  return JSON.stringify(manifest, null, 2)
}

// Main execution
const serviceName = process.argv[2] || 'pocket'
const consumerKey = process.argv[3] || '__consumerKey__'

if (!serviceName) {
  console.error('Usage: node build-for-service.js [service-name] [consumer-key]')
  process.exit(1)
}

console.log(`Building extension for ${serviceName} service...`)

// Generate config file
const configContent = generateConfigFile(serviceName, consumerKey)
fs.writeFileSync(path.join(__dirname, '../src/common/config.js'), configContent)
console.log('✓ Generated config.js')

// Generate manifest
const manifestContent = generateManifest(serviceName)
fs.writeFileSync(path.join(__dirname, '../src/manifest.json'), manifestContent)
console.log('✓ Generated manifest.json')

console.log(`\nConfiguration complete for ${serviceName}!`)
console.log('Run "npm run build" to build the extension.')

if (consumerKey === '__consumerKey__') {
  console.log('\n⚠️  Warning: Using placeholder consumer key. Replace with actual key before production.')
}